#!/usr/bin/env node

import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { stdin, stdout } from 'node:process';
import { createInterface } from 'node:readline/promises';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const scriptPath = fileURLToPath(import.meta.url);
const templateRoot = path.resolve(path.dirname(scriptPath), '..');
const TEMPLATE_ENTRIES = [
  '.codex',
  '.env.example',
  '.gitignore',
  'AGENTS.md',
  'LICENSE',
  'README.md',
  'app',
  'app.json',
  'assets',
  'bin',
  'eslint.config.js',
  'package-lock.json',
  'package.json',
  'src',
  'tsconfig.json',
];

function slugify(input) {
  return input
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40);
}

function formatDefault(value) {
  return value ? ` (${value})` : '';
}

async function askText(rl, question, defaultValue = '') {
  const answer = (await rl.question(`${question}${formatDefault(defaultValue)}: `)).trim();
  return answer || defaultValue;
}

async function askChoice(rl, question, choices, defaultValue) {
  const label = choices.map((value, index) => `${index + 1}.${value}`).join(' ');
  const raw = await askText(rl, `${question} ${label}`, defaultValue);

  const asIndex = Number(raw);
  if (!Number.isNaN(asIndex) && asIndex >= 1 && asIndex <= choices.length) {
    return choices[asIndex - 1];
  }

  if (choices.includes(raw)) {
    return raw;
  }

  return defaultValue;
}

async function askYesNo(rl, question, defaultValue = true) {
  const hint = defaultValue ? 'Y/n' : 'y/N';
  const raw = (await rl.question(`${question} (${hint}): `)).trim().toLowerCase();

  if (!raw) {
    return defaultValue;
  }

  return raw === 'y' || raw === 'yes';
}

function readJson(filePath) {
  if (!existsSync(filePath)) {
    return null;
  }

  return JSON.parse(readFileSync(filePath, 'utf-8'));
}

function writeJson(filePath, value) {
  writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`, 'utf-8');
}

function readCurrentAppName(projectDir) {
  const appJsonPath = path.join(projectDir, 'app.json');
  const parsed = readJson(appJsonPath);
  return parsed?.expo?.name || path.basename(projectDir) || 'BlinkStackApp';
}

function updateAppJson(projectDir, appName, slug) {
  const appJsonPath = path.join(projectDir, 'app.json');
  const parsed = readJson(appJsonPath);
  if (!parsed) {
    return;
  }

  parsed.expo = parsed.expo ?? {};
  parsed.expo.name = appName;
  parsed.expo.slug = slug;

  writeJson(appJsonPath, parsed);
}

function updatePackageJsonForProject(projectDir, slug) {
  const packageJsonPath = path.join(projectDir, 'package.json');
  const parsed = readJson(packageJsonPath);
  if (!parsed) {
    return;
  }

  parsed.name = slug || parsed.name;
  parsed.private = true;
  delete parsed.bin;
  delete parsed.files;
  delete parsed.publishConfig;

  writeJson(packageJsonPath, parsed);
}

function writeEnvFile(projectDir, config) {
  const envLocalPath = path.join(projectDir, '.env.local');
  const lines = [
    '# Generated by blink-stack-mobile CLI',
    `EXPO_PUBLIC_AUTH_PROVIDER=${config.authProvider}`,
    `EXPO_PUBLIC_NOTIFICATION_PROVIDER=${config.notificationProvider}`,
    `EXPO_PUBLIC_CLERK_PUBLISHABLE_KEY=${config.clerkPublishableKey}`,
    `EXPO_PUBLIC_SUPABASE_URL=${config.supabaseUrl}`,
    `EXPO_PUBLIC_SUPABASE_ANON_KEY=${config.supabaseAnonKey}`,
    `EXPO_PUBLIC_APPWRITE_ENDPOINT=${config.appwriteEndpoint}`,
    `EXPO_PUBLIC_APPWRITE_PROJECT_ID=${config.appwriteProjectId}`,
    `EXPO_PUBLIC_REVENUECAT_API_KEY_IOS=${config.revenueCatIos}`,
    `EXPO_PUBLIC_REVENUECAT_API_KEY_ANDROID=${config.revenueCatAndroid}`,
    `EXPO_PUBLIC_REVENUECAT_ENTITLEMENT_ID=${config.revenueCatEntitlement}`,
    `EXPO_PUBLIC_ONESIGNAL_APP_ID=${config.oneSignalAppId}`,
    `EXPO_PUBLIC_NOVU_API_URL=${config.novuApiUrl}`,
    `EXPO_PUBLIC_NOVU_API_KEY=${config.novuApiKey}`,
    `EXPO_PUBLIC_NOVU_SUBSCRIBER_ID=${config.novuSubscriberId}`,
    `EXPO_PUBLIC_SENTRY_DSN=${config.sentryDsn}`,
    '',
  ];

  writeFileSync(envLocalPath, lines.join('\n'), 'utf-8');
}

function assertEmptyOrMissingDir(targetDir) {
  if (!existsSync(targetDir)) {
    mkdirSync(targetDir, { recursive: true });
    return;
  }

  const currentEntries = readdirSync(targetDir);
  if (currentEntries.length > 0) {
    throw new Error(`Target directory is not empty: ${targetDir}`);
  }
}

function copyTemplateTo(targetDir) {
  for (const entry of TEMPLATE_ENTRIES) {
    const source = path.join(templateRoot, entry);
    if (!existsSync(source)) {
      continue;
    }

    const destination = path.join(targetDir, entry);
    cpSync(source, destination, { recursive: true });
  }
}

function printUsage() {
  stdout.write('Usage:\n');
  stdout.write('  blink-stack-mobile init <project-name>\n');
  stdout.write('  blink-stack-mobile configure\n');
  stdout.write('  blink-stack-mobile\n');
}

async function configureProject(projectDir) {
  const rl = createInterface({ input: stdin, output: stdout });

  try {
    const currentAppName = readCurrentAppName(projectDir);
    const appName = await askText(rl, 'App name', currentAppName);
    const slug = await askText(rl, 'App slug', slugify(appName));

    const authProvider = await askChoice(rl, 'Auth provider', ['basic', 'clerk', 'supabase', 'appwrite'], 'basic');
    const notificationProvider = await askChoice(rl, 'Notification provider', ['none', 'onesignal', 'novu'], 'none');

    const config = {
      authProvider,
      notificationProvider,
      clerkPublishableKey: '',
      supabaseUrl: '',
      supabaseAnonKey: '',
      appwriteEndpoint: '',
      appwriteProjectId: '',
      revenueCatIos: '',
      revenueCatAndroid: '',
      revenueCatEntitlement: 'pro',
      oneSignalAppId: '',
      novuApiUrl: '',
      novuApiKey: '',
      novuSubscriberId: '',
      sentryDsn: '',
    };

    if (authProvider === 'clerk') {
      config.clerkPublishableKey = await askText(rl, 'Clerk publishable key');
    }

    if (authProvider === 'supabase') {
      config.supabaseUrl = await askText(rl, 'Supabase URL');
      config.supabaseAnonKey = await askText(rl, 'Supabase anon key');
    }

    if (authProvider === 'appwrite') {
      config.appwriteEndpoint = await askText(rl, 'Appwrite endpoint');
      config.appwriteProjectId = await askText(rl, 'Appwrite project id');
    }

    const useRevenueCat = await askYesNo(rl, 'Configure RevenueCat subscription keys now?', true);
    if (useRevenueCat) {
      config.revenueCatIos = await askText(rl, 'RevenueCat iOS API key');
      config.revenueCatAndroid = await askText(rl, 'RevenueCat Android API key');
      config.revenueCatEntitlement = await askText(rl, 'RevenueCat entitlement id', 'pro');
    }

    if (notificationProvider === 'onesignal') {
      config.oneSignalAppId = await askText(rl, 'OneSignal app id');
    }

    if (notificationProvider === 'novu') {
      config.novuApiUrl = await askText(rl, 'Novu API base URL', 'https://api.novu.co');
      config.novuApiKey = await askText(rl, 'Novu API key');
      config.novuSubscriberId = await askText(rl, 'Novu subscriber id');
    }

    const useSentry = await askYesNo(rl, 'Configure Sentry now?', true);
    if (useSentry) {
      config.sentryDsn = await askText(rl, 'Sentry DSN');
    }

    updateAppJson(projectDir, appName, slug);
    updatePackageJsonForProject(projectDir, slug);
    writeEnvFile(projectDir, config);

    stdout.write(`\nCreated ${path.join(projectDir, '.env.local')}\n`);
    stdout.write(`Updated ${path.join(projectDir, 'app.json')}\n`);
    stdout.write(`Updated ${path.join(projectDir, 'package.json')}\n\n`);
  } finally {
    rl.close();
  }
}

function installDependencies(projectDir) {
  const result = spawnSync('npm', ['install'], {
    cwd: projectDir,
    stdio: 'inherit',
  });

  if (result.status !== 0) {
    throw new Error('Dependency installation failed.');
  }
}

async function initProject(projectName) {
  const targetDir = path.resolve(process.cwd(), projectName);

  assertEmptyOrMissingDir(targetDir);
  copyTemplateTo(targetDir);

  stdout.write(`Scaffolded project in ${targetDir}\n\n`);

  await configureProject(targetDir);

  const rl = createInterface({ input: stdin, output: stdout });
  try {
    const shouldInstall = await askYesNo(rl, 'Install dependencies now?', true);
    if (shouldInstall) {
      installDependencies(targetDir);
    }
  } finally {
    rl.close();
  }

  stdout.write('Next steps:\n');
  stdout.write(`1. cd ${projectName}\n`);
  stdout.write('2. npm run lint\n');
  stdout.write('3. npm run typecheck\n');
  stdout.write('4. npm run ios (or android/web)\n');
}

async function run() {
  const args = process.argv.slice(2);
  const command = args[0];

  if (!command || command === 'configure') {
    await configureProject(process.cwd());
    return;
  }

  if (command === 'init') {
    const projectName = args[1];
    if (!projectName) {
      printUsage();
      throw new Error('Missing <project-name> for init command.');
    }

    await initProject(projectName);
    return;
  }

  if (command === '--help' || command === '-h' || command === 'help') {
    printUsage();
    return;
  }

  printUsage();
  throw new Error(`Unknown command: ${command}`);
}

void run();
